import assert from 'node:assert/strict';
import { access, readFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
const root = new URL('../', import.meta.url);
const worker = new URL('../dist/server/index.js', import.meta.url);
const client = new URL('../client.js', import.meta.url);
const sourceHtml = await readFile(new URL('../index.html', import.meta.url), 'utf8');
const sourceClient = await readFile(client, 'utf8');
const html = await readFile(worker, 'utf8');
assert.match(html, /export default \{ async fetch/);
assert.match(html, /VLADYERIK ARCADE/);
assert.match(html, /\?room=/);
assert.match(html, /online_rooms/);
assert.match(sourceHtml, /Jugar contra la computadora/);
assert.match(sourceHtml, /Jugar online/);
assert.match(sourceHtml, /data-difficulty=\"hard\"/);
assert.match(html, /VladyerikSolo/);
assert.match(html, /heartbeat/);
assert.doesNotMatch(sourceClient, /else \{heartbeat\(\);/);
const clientSyntax = spawnSync(process.execPath, ['--check', client.pathname], { encoding: 'utf8' });
assert.equal(clientSyntax.status, 0, clientSyntax.stderr);
await access(new URL('../dist/.openai/hosting.json', import.meta.url));
const syntax = spawnSync(process.execPath, ['--check', worker.pathname], { encoding: 'utf8' });
assert.equal(syntax.status, 0, syntax.stderr);
await import(worker.href);
console.log('Worker ESM and packaged assets are valid.');
